namespace VK_UI3.Controls.BetterLyric;

public partial class LyricData
{
    public List<LyricLine> LyricsLines { get; set; } = [];
    public bool AutoGenerated { get; set; } = false;

    /// <summary>
    /// Текст без таймингов (нет синхронизации с плеером).
    /// <para>
    /// Для такого текста отключается привязка к позиции воспроизведения,
    /// подсветка «играющей» строки и посимвольные эффекты: строки просто
    /// отображаются списком и прокручиваются пользователем.
    /// </para>
    /// </summary>
    public bool IsUntimed { get; set; } = false;

    public string WrappedOriginalText => string.Join("\n", LyricsLines.Select(line => line.PrimaryText));
    public bool IsWordByWord => LyricsLines.Any(x => x.IsPrimaryHasRealSyllableInfo);
    public TimeSpan Duration => TimeSpan.FromMilliseconds(LyricsLines?.Max(l => l.EndMs) ?? 0);
    public LyricData()
    {
    }

    public LyricData(List<LyricLine> lyricsLines)
    {
        LyricsLines = lyricsLines;
    }

    /// <summary>
    /// Создаёт данные статичного (без таймингов) текста.
    /// </summary>
    public static LyricData CreateUntimed(List<LyricLine> lyricsLines)
    {
        return new LyricData(lyricsLines) { IsUntimed = true };
    }

}
